-- Corrige o travessao UTF-8 que foi lido como CP850 em nomes de perfis Part 145.
UPDATE perfil
SET nome = REPLACE(
    nome,
    CONVERT(0x506172742031343520C394C387C3B620 USING utf8mb4),
    CONVERT(0x506172742031343520E2809420 USING utf8mb4)
)
WHERE codigo IN ('P145_RT', 'P145_INSPETOR', 'P145_EXECUCAO', 'P145_ALMOX', 'P145_COMERCIAL')
  AND LOCATE(0x506172742031343520C394C387C3B620, CAST(nome AS BINARY)) = 1;
